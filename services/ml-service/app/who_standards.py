# PUBLIC API
# ─────────────────────────────────────────────────────────────────────────────

def calculate_z_score(age_months: int, value: float, gender: str,
                       measurement_type: str) -> float:
    """Return WHO z-score. measurement_type: 'height' | 'weight'"""
    L, M, S = _get_lms(age_months, gender, measurement_type)
    if abs(L) < 1e-6:
        z = math.log(value / M) / S
    else:
        z = ((value / M) ** L - 1) / (L * S)
    return round(z, 3)


def calculate_percentile(age_months: int, value: float, gender: str,
                          measurement_type: str) -> float:
    """Return percentile (0–100)."""
    z = calculate_z_score(age_months, value, gender, measurement_type)
    return round(_norm_cdf(z) * 100, 1)


def evaluate_measurement(age_months: int, value: float, gender: str,
                           measurement_type: str) -> dict:
    """
    Clinical evaluation of a single measurement.

    Returns:
        percentile  : float 0–100
        z_score     : float
        status      : 'normal' | 'monitor' | 'concern' | 'severe_concern'
        warnings    : list[str]
    """
    z = calculate_z_score(age_months, value, gender, measurement_type)
    pct = round(_norm_cdf(z) * 100, 1)

    warnings = []
    if z < -3:
        status = "severe_concern"
        warnings.append(f"{measurement_type.capitalize()} is severely below expected range (z={z:.1f})")
    elif z < -2:
        status = "concern"
        warnings.append(f"{measurement_type.capitalize()} is below expected range (z={z:.1f})")
    elif z < -1:
        status = "monitor"
    elif z > 3:
        status = "severe_concern"
        warnings.append(f"{measurement_type.capitalize()} is severely above expected range (z={z:.1f})")
    elif z > 2:
        status = "concern"
        warnings.append(f"{measurement_type.capitalize()} is above expected range (z={z:.1f})")
    else:
        status = "normal"

    return {
        "percentile": pct,
        "z_score": z,
        "status": status,
        "warnings": warnings,
    }


def check_percentile_crossing(old_pct: float, new_pct: float,
                                measurement_type: str) -> dict | None:
    """
    Detect significant percentile channel crossing (>15 points drop).
    Returns a warning dict or None.
    """
    delta = old_pct - new_pct  # positive = dropped
    if delta >= 15:
        return {
            "type": "percentile_crossing",
            "severity": "high" if delta >= 25 else "medium",
            "message": f"{measurement_type.capitalize()} dropped {delta:.0f} percentile points",
            "delta": round(delta, 1),
        }
    return None
