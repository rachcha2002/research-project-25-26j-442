_LMS_TABLES = {
    "boys":  {"height": BOYS_HEIGHT_LMS,  "weight": BOYS_WEIGHT_LMS},
    "girls": {"height": GIRLS_HEIGHT_LMS, "weight": GIRLS_WEIGHT_LMS},
}


def _get_lms(age_months: int, gender: str, measurement_type: str) -> tuple:
    """Return (L, M, S) for given age, gender, type. Clamps to 0–84."""
    gender_key = "boys" if gender.lower() in ("male", "boy", "m", "1") else "girls"
    table = _LMS_TABLES[gender_key][measurement_type]
    age = max(0, min(84, age_months))
    # If exact age not in table, interpolate between nearest months
    if age in table:
        return table[age]
    ages_sorted = sorted(table.keys())
    lower = max((a for a in ages_sorted if a <= age), default=ages_sorted[0])
    upper = min((a for a in ages_sorted if a >= age), default=ages_sorted[-1])
    if lower == upper:
        return table[lower]
    t = (age - lower) / (upper - lower)
    L = table[lower][0] + t * (table[upper][0] - table[lower][0])
    M = table[lower][1] + t * (table[upper][1] - table[lower][1])
    S = table[lower][2] + t * (table[upper][2] - table[lower][2])
    return (L, M, S)


def _norm_cdf(z: float) -> float:
    """Approximation of the normal CDF (no scipy dependency required)."""
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


